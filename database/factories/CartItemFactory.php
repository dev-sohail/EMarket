<?php

namespace Database\Factories;

use App\Models\Cart;
use App\Models\Product;
use App\Models\ProductVariant;
use Illuminate\Database\Eloquent\Factories\Factory;

class CartItemFactory extends Factory
{
    public function definition(): array
    {
        return [
            'cart_id' => Cart::factory(),
            'product_id' => Product::factory(),
            'variant_id' => null,
            'quantity' => fake()->numberBetween(1, 3),
            'unit_price' => fake()->randomFloat(2, 100, 5000),
        ];
    }

    /**
     * `carts` has no `id` column — the primary key is the prefixed `_id`
     * generated by `PrefixedId`. `getKey()` reads it directly rather than
     * relying on the `id` alias accessor, which only returns a value for an
     * already-persisted model and is `null` for an unsaved one.
     */
    public function forCart(Cart $cart): static
    {
        return $this->state(fn (array $attributes) => [
            'cart_id' => $cart->getKey(),
        ]);
    }

    /**
     * `products.base_price` is the real column name, but `unit_price` is a
     * snapshot of the *payable* price, which is what
     * `CartService::resolveCurrentPrice()` writes via
     * `PricingService::resolveUnitPrice()` — `Product::final_price`, so
     * `sale_price` and `discount_type`/`discount_value` are already applied.
     * Seeding the snapshot from `base_price` made the row disagree with every
     * figure produced from it.
     */
    public function forProduct(Product $product): static
    {
        return $this->state(fn (array $attributes) => [
            'product_id' => $product->getKey(),
            'unit_price' => (float) $product->final_price,
        ]);
    }

    /**
     * A line for a variant. The snapshot is `ProductVariant::final_price`, so
     * `sale_price` and `price_add_to_main` are included, matching the price the
     * cart and the checkout charge for that line.
     */
    public function forVariant(ProductVariant $variant): static
    {
        $variant->loadMissing('product');

        return $this->state(fn (array $attributes) => [
            'product_id' => $variant->product_id,
            'variant_id' => $variant->getKey(),
            'unit_price' => (float) $variant->final_price,
        ]);
    }
}
